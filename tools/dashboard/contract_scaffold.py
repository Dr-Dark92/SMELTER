"""Generate a parseable Lua skeleton from a frozen contract's structured interface.

Local models repeatedly failed to write a whole contract subject in one pass:
syntax errors, then restoring an older invented interface. The scaffold makes
the interface itself (constructor, dependency/capability/profile validation,
method signatures, return shapes) correct by construction, and leaves only
small, named behaviour helpers for the model to fill in and test one at a time.

The spec lives in operator-reviewed acceptance definitions; nothing here knows
about any game. Output is a normal reviewable proposal, never applied directly.
"""
import re

_NAME = re.compile(r'[A-Za-z_][A-Za-z0-9_]*$')
_TYPES = ('table', 'function', 'number', 'string', 'boolean')
_OPS = ('<=', '<', '>=', '>')


def _name(value):
    if not isinstance(value, str) or not _NAME.match(value) or len(value) > 48:
        raise ValueError('Scaffold names must be Lua identifiers')
    return value


def _args(values):
    if not isinstance(values, list) or len(values) > 8:
        raise ValueError('Scaffold arguments are a short list')
    # A trailing vararg lets plumbing helpers forward any adapter arguments.
    return [v if v == '...' and i == len(values) - 1 else _name(v) for i, v in enumerate(values)]


def _comment(value):
    return ' '.join(str(value).split())[:300]


def _wrapped(indent, value):
    import textwrap
    return [indent + '-- ' + line for line in textwrap.wrap(_comment(value), 110 - len(indent))] or [indent + '--']


def render(contract_id, spec):
    """Return Lua source for the spec; raises ValueError on a malformed spec."""
    if not isinstance(spec, dict):
        raise ValueError('Contract has no scaffold specification')
    constructor = _name(spec.get('constructor', 'new'))
    lines = ['-- Scaffold generated by SMELTER from frozen contract ' + _comment(contract_id) + '.',
             '-- The constructor validation and method shapes match the contract interface.',
             '-- Fill in ONE helper at a time (search for TODO), then run the tests.',
             '-- Pure module: no os, io, require, print, _G or module-level mutable state.',
             'local M = {}', '']
    helpers = spec.get('helpers', [])
    if not isinstance(helpers, list) or len(helpers) > 12:
        raise ValueError('Scaffold helpers must be a list of at most twelve entries')
    lines += ['function M.' + constructor + '(deps)',
              '  if type(deps) ~= "table" then', '    return nil, "deps_not_table"', '  end']
    for dep in spec.get('deps', []):
        name, kind = _name(dep.get('name')), dep.get('type')
        if kind not in _TYPES:
            raise ValueError('Unsupported scaffold dependency type')
        lines += ['  if type(deps.' + name + ') ~= "' + kind + '" then',
                  '    return nil, "' + name + '_must_be_' + kind + '"', '  end']
        for function in dep.get('functions', []):
            function = _name(function)
            lines += ['  if type(deps.' + name + '.' + function + ') ~= "function" then',
                      '    return nil, "unsupported_capability:' + function + '"', '  end']
        for number in dep.get('numbers', []):
            number = _name(number)
            lines += ['  do', '    local value = deps.' + name + '.' + number,
                      '    if type(value) ~= "number" or value ~= value or value < 0 then',
                      '      return nil, "' + name + '_invalid:' + number + '"', '    end', '  end']
        for rule in dep.get('rules', []):
            if not (isinstance(rule, list) and len(rule) == 3 and rule[1] in _OPS):
                raise ValueError('Scaffold rules are [left, operator, right]')
            left, right = _name(rule[0]), _name(rule[2])
            lines += ['  if not (deps.' + name + '.' + left + ' ' + rule[1] + ' deps.' + name + '.' + right + ') then',
                      '    return nil, "' + name + '_rule:' + left + '_' + {'<=': 'le', '<': 'lt', '>=': 'ge', '>': 'gt'}[rule[1]] + '_' + right + '"',
                      '  end']
    lines += ['', '  -- Per-instance state lives here, never at module level.',
              '  local state = {}', '  local controller = {}', '']
    for helper in helpers:
        name = _name(helper.get('name'))
        args = _args(helper.get('args', []))
        body = helper.get('body')
        lines += _wrapped('  ', name + ': ' + helper.get('doc', ''))
        lines.append('  local function ' + name + '(' + ', '.join(args) + ')')
        if body is None:
            lines += ['    -- TODO: implement ' + name + ' (keep it short; one statement per line).',
                      '    return ' + helper.get('stub', 'nil'), '  end', '']
            continue
        if not isinstance(body, list) or len(body) > 30 or any(not isinstance(b, str) or len(b) > 110 for b in body):
            raise ValueError('Scaffold helper bodies are at most 30 short lines')
        lines += ['    ' + b for b in body] + ['  end', '']
    methods = spec.get('methods', [])
    if not isinstance(methods, list) or not 1 <= len(methods) <= 6:
        raise ValueError('Scaffold needs one to six methods')
    for method in methods:
        name = _name(method.get('name'))
        args = _args(method.get('args', []))
        for step in method.get('steps', [])[:8]:
            lines += _wrapped('  ', step)
        lines += _wrapped('  ', name + ' returns ' + method.get('returns', ''))
        lines += [
                  '  function controller:' + name + '(' + ', '.join(args) + ')',
                  '    -- TODO: implement using the helpers above.',
                  '    return ' + method.get('stub', 'nil'), '  end', '']
    lines += ['  return controller', 'end', '', 'return M', '']
    return '\n'.join(lines)


def scaffold(root, arguments):
    """Propose (not apply) a scaffold for a registered contract subject."""
    import coding_workspace as cw
    from acceptance_contracts import DEFINITIONS, load
    if set(arguments) != {'workspace_id', 'contract_id'}:
        raise ValueError('Scaffold requires workspace_id and contract_id')
    with cw.locked(root):
        _, target = cw.load(root, arguments['workspace_id'])
        contracts = [c for c in load(root, arguments['workspace_id'], target) if c['id'] == arguments['contract_id']]
        if not contracts:
            raise ValueError('Contract is not registered for this workspace')
        spec = DEFINITIONS[arguments['contract_id']].get('scaffold')
        if spec is None:
            raise ValueError('This contract has no scaffold specification; edit the subject directly')
        relative = contracts[0]['subject_path']
        path = cw._file(target, relative, edit=True)
        current = cw.digest(path.read_bytes()) if path.is_file() else None
        content = render(arguments['contract_id'], spec)
        changes = cw._changes(target, [{'relative_path': relative, 'expected_sha256': current, 'content': content}], True)
        syntax = cw._lua_gate(root, target, changes)
        result = cw._with_syntax(cw._record_proposal(root, arguments['workspace_id'], changes), syntax)
        result.update(scaffold_for=arguments['contract_id'],
                      todo=[h['name'] for h in spec.get('helpers', []) if h.get('body') is None] +
                           [m['name'] for m in spec.get('methods', [])],
                      next_steps='Apply this proposal, run_coding_tests profile=lua (constructor checks should pass), '
                                 'then implement one TODO helper at a time with propose_coding_edit and rerun tests.')
        return result
